import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { DEPENDABOT_TEMPLATE } from './__fixtures__/dependabot-template.ts';
import { fakeLog } from './__fixtures__/log.ts';
import {
  createFileResponse,
  createHttpError,
  fakeOctokit,
} from './__fixtures__/octokit.ts';
import {
  detectEcosystems,
  loadDependabotTemplate,
  parseDependabotTemplate,
  planDependabotChange,
} from './dependabot-config.ts';

describe('parseDependabotTemplate', () => {
  it('indexes the entries by ecosystem', () => {
    const template = parseDependabotTemplate(DEPENDABOT_TEMPLATE);
    assert.deepEqual(
      [...template.entryByEcosystem.keys()],
      ['npm', 'docker', 'github-actions'],
    );
    assert.equal(template.doc.get('version'), 2);
  });
});

describe('loadDependabotTemplate', () => {
  it('fetches the template from the org .github repo', async () => {
    const octokit = fakeOctokit({
      'repos.getContent': () =>
        createFileResponse('templates/dependabot.yaml', DEPENDABOT_TEMPLATE),
    });
    const template = await loadDependabotTemplate(octokit);
    assert.deepEqual(octokit.calls[0].params, {
      owner: 'verkstedt',
      repo: '.github',
      path: 'templates/dependabot.yaml',
    });
    assert.equal(template.entryByEcosystem.size, 3);
  });

  it('fails when the template is missing', async () => {
    const octokit = fakeOctokit({
      'repos.getContent': () => {
        throw createHttpError(404);
      },
    });
    await assert.rejects(loadDependabotTemplate(octokit), {
      message: /templates\/dependabot\.yaml/,
    });
  });
});

/** `detectEcosystems` for a tree of `paths` with the given file contents. */
function detect(paths: Array<string>, files: Record<string, string> = {}) {
  return detectEcosystems({
    listPaths: async () => paths,
    readFile: async (path) =>
      path in files ? { path, content: files[path] } : null,
  });
}

const UV_COMPILED =
  '# This file was autogenerated by uv via the following command:\n#    uv pip compile requirements.in -o requirements.txt\nfoo==1.0\n';

describe('detectEcosystems', () => {
  it('finds nothing in an empty tree', async () => {
    assert.deepEqual(await detect([]), {
      detected: new Set(),
      manifestDirsByEcosystem: new Map(),
      requiredCodeowners: [],
    });
  });

  it('collects the directories manifests are in', async () => {
    const { manifestDirsByEcosystem } = await detect([
      '/package.json',
      '/packages/a/package.json',
      '/pnpm-lock.yaml',
      '/Cargo.lock',
      '/api/requirements.txt',
      '/.docker/Dockerfile.build',
      '/deploy/docker-compose.yml',
      '/.devcontainer/devcontainer.json',
      '/.github/workflows/ci.yaml',
    ]);
    assert.deepEqual(
      manifestDirsByEcosystem,
      new Map([
        ['npm', new Set(['/'])],
        ['cargo', new Set(['/'])],
        ['pip', new Set(['/api'])],
        ['docker', new Set(['/.docker'])],
        ['docker-compose', new Set(['/deploy'])],
      ]),
    );
  });

  it('detects npm from lockfiles and requires an owner for them', async () => {
    const { detected, requiredCodeowners } = await detect([
      '/package.json',
      '/packages/a/package.json',
      '/packages/a/pnpm-lock.yaml',
    ]);
    assert.deepEqual([...detected], ['npm']);
    assert.deepEqual(requiredCodeowners, ['pnpm-lock.yaml']);
  });

  it('ignores manifests without lockfiles', async () => {
    assert.deepEqual(await detect(['/package.json', '/Cargo.toml']), {
      detected: new Set(),
      manifestDirsByEcosystem: new Map(),
      requiredCodeowners: [],
    });
  });

  it('detects cargo and requires an owner for its lockfile', async () => {
    const { detected, requiredCodeowners } = await detect([
      '/Cargo.toml',
      '/crates/a/Cargo.toml',
      '/Cargo.lock',
    ]);
    assert.deepEqual([...detected], ['cargo']);
    assert.deepEqual(requiredCodeowners, ['Cargo.lock']);
  });

  it('detects pip from requirements files', async () => {
    const { detected, requiredCodeowners } = await detect(
      ['/requirements.txt', '/requirements.in', '/api/requirements-dev.txt'],
      {
        '/requirements-dev.txt':
          '#\n# This file is autogenerated by pip-compile with Python 3.12\n#\nbar==2.0\n',
      },
    );
    assert.deepEqual([...detected], ['pip']);
    assert.deepEqual(requiredCodeowners, [
      'requirements-dev.txt',
      'requirements.in',
      'requirements.txt',
    ]);
  });

  it('ignores Python projects without requirements files or lockfiles', async () => {
    assert.deepEqual(await detect(['/pyproject.toml', '/setup.py']), {
      detected: new Set(),
      manifestDirsByEcosystem: new Map(),
      requiredCodeowners: [],
    });
  });

  it('detects uv instead of pip next to a uv.lock', async () => {
    const { detected, manifestDirsByEcosystem, requiredCodeowners } =
      await detect([
        '/pyproject.toml',
        '/uv.lock',
        '/requirements.txt',
        '/requirements.in',
      ]);
    assert.deepEqual([...detected], ['uv']);
    assert.deepEqual(manifestDirsByEcosystem.get('uv'), new Set(['/']));
    assert.deepEqual(requiredCodeowners, [
      'requirements.in',
      'requirements.txt',
      'uv.lock',
    ]);
  });

  it('does not read requirements next to a uv.lock', async () => {
    const { detected } = await detectEcosystems({
      listPaths: async () => ['/uv.lock', '/requirements.txt'],
      readFile: async (path) => {
        throw new Error(`unexpected read of ${path}`);
      },
    });
    assert.deepEqual([...detected], ['uv']);
  });

  it('detects uv for requirements generated by uv pip compile', async () => {
    const { detected, manifestDirsByEcosystem } = await detect(
      ['/requirements.in', '/requirements.txt', '/api/requirements.txt'],
      {
        '/requirements.txt': UV_COMPILED,
        '/api/requirements.txt': 'baz==3.0\n',
      },
    );
    assert.deepEqual([...detected], ['uv', 'pip']);
    assert.deepEqual(manifestDirsByEcosystem.get('uv'), new Set(['/']));
    assert.deepEqual(manifestDirsByEcosystem.get('pip'), new Set(['/api']));
  });

  it('detects docker, compose files, devcontainers and workflows', async () => {
    const { detected, requiredCodeowners } = await detect([
      '/Dockerfile',
      '/images/base.Dockerfile',
      '/Dockerfile.worker',
      '/services/Dockerfile.worker',
      '/Containerfile',
      '/docker-compose.yml',
      '/compose.yaml',
      '/deploy/docker-compose.prod.yaml',
      '/deploy/docker-compose.yml',
      '/.devcontainer/devcontainer.json',
      '/.github/workflows/ci.yaml',
    ]);
    assert.deepEqual(
      [...detected],
      ['docker', 'docker-compose', 'devcontainers', 'github-actions'],
    );
    assert.deepEqual(requiredCodeowners, [
      'Containerfile',
      'Dockerfile',
      'Dockerfile.worker',
      'base.Dockerfile',
      'compose.yaml',
      'docker-compose.prod.yaml',
      'docker-compose.yml',
      '/.devcontainer/devcontainer.json',
      '/.github/workflows/',
    ]);
  });
});

describe('planDependabotChange', () => {
  const template = parseDependabotTemplate(DEPENDABOT_TEMPLATE);
  const log = fakeLog();
  const warnings = log.calls.warning;

  it('does nothing when no ecosystem was detected', () => {
    const change = planDependabotChange({
      detected: new Set(),
      manifestDirsByEcosystem: new Map(),
      existing: null,
      template,
      defaultBranch: 'main',
      log,
    });
    assert.equal(change, null);
  });

  it('creates a config from the template with only detected ecosystems', () => {
    const change = planDependabotChange({
      detected: new Set(['npm']),
      manifestDirsByEcosystem: new Map(),
      existing: null,
      template,
      defaultBranch: 'main',
      log,
    });
    assert.ok(change);
    assert.equal(change.path, '.github/dependabot.yaml');
    assert.equal(change.sha, undefined);
    assert.match(change.newContent, /^# Org template\n/);
    assert.match(
      change.newContent,
      /# JavaScript\n\s+- package-ecosystem: 'npm'/,
    );
    assert.match(change.newContent, /\n {4}exclude-paths: \[\]\n/);
    assert.doesNotMatch(change.newContent, /docker|github-actions/);
    assert.equal(
      change.summary,
      'created `.github/dependabot.yaml` with sections: `npm`',
    );
  });

  it('does nothing for an unknown ecosystem with no file', () => {
    const change = planDependabotChange({
      detected: new Set(['devcontainers']),
      manifestDirsByEcosystem: new Map(),
      existing: null,
      template,
      defaultBranch: 'main',
      log,
    });
    assert.equal(change, null);
  });

  it('adds missing ecosystems and a cooldown, matching the quote style', () => {
    const existing = {
      path: '.github/dependabot.yml',
      sha: 'old',
      content: [
        'version: 2',
        'updates:',
        '  - package-ecosystem: "npm"',
        '    directory: "/"',
        '    schedule:',
        '      interval: "daily"',
        '    cooldown:',
        '      default-days: 3',
        '',
      ].join('\n'),
    };
    const change = planDependabotChange({
      detected: new Set(['npm', 'docker']),
      manifestDirsByEcosystem: new Map(),
      existing,
      template,
      defaultBranch: 'main',
      log,
    });
    assert.ok(change);
    assert.equal(change.path, '.github/dependabot.yml');
    assert.equal(change.sha, 'old');
    assert.match(change.newContent, /interval: "daily"/);
    assert.match(change.newContent, /default-days: 7/);
    assert.match(change.newContent, /package-ecosystem: "docker"/);
    assert.doesNotMatch(change.newContent, /'/);
    assert.equal(
      change.summary,
      'updated `.github/dependabot.yml`: added sections: `docker`; set `cooldown.default-days: 7` on `npm`',
    );
  });

  it('leaves a complete config alone', () => {
    const change = planDependabotChange({
      detected: new Set(['npm', 'docker']),
      manifestDirsByEcosystem: new Map(),
      existing: { path: 'x', sha: 's', content: DEPENDABOT_TEMPLATE },
      template,
      defaultBranch: 'main',
      log,
    });
    assert.equal(change, null);
  });

  it('adds an updates list to a file without one', () => {
    const change = planDependabotChange({
      detected: new Set(['npm']),
      manifestDirsByEcosystem: new Map(),
      existing: { path: 'x', sha: 's', content: 'version: 2\n' },
      template,
      defaultBranch: 'main',
      log,
    });
    assert.ok(change);
    assert.match(change.newContent, /^version: 2\nupdates:\n/);
    assert.match(change.newContent, /package-ecosystem: 'npm'/);
    assert.equal(change.summary, 'updated `x`: added sections: `npm`');
  });

  it('adds a missing version to an otherwise complete file', () => {
    const change = planDependabotChange({
      detected: new Set(['npm', 'docker']),
      manifestDirsByEcosystem: new Map(),
      existing: {
        path: 'x',
        sha: 's',
        content: DEPENDABOT_TEMPLATE.replace(/^version: 2\n/m, ''),
      },
      template,
      defaultBranch: 'main',
      log,
    });
    assert.ok(change);
    assert.match(change.newContent, /^version: 2\n/m);
    assert.equal(change.summary, 'updated `x`: set `version: 2`');
  });

  describe('directories', () => {
    const createExisting = (...entryLines: Array<string>) => ({
      path: 'x',
      sha: 's',
      content: [
        'version: 2',
        'updates:',
        "  - package-ecosystem: 'npm'",
        ...entryLines.map((line) => `    ${line}`),
        '    cooldown:',
        '      default-days: 7',
        '',
      ].join('\n'),
    });

    it('copies the template’s directories in place when manifests are not covered', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([['npm', new Set(['/', '/web'])]]),
        existing: createExisting(
          "directory: '/'",
          "versioning-strategy: 'increase'",
        ),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.ok(change);
      assert.doesNotMatch(change.newContent, /directory:|exclude-paths/);
      assert.match(
        change.newContent,
        /'npm'\n {4}directories:\n {6}- '\/\*\*'\n {4}versioning-strategy:/,
      );
      assert.equal(
        change.summary,
        'updated `x`: set directories on `npm` to match the template',
      );
    });

    it('replaces a list of directories that misses some manifests', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([['npm', new Set(['/a', '/b'])]]),
        existing: createExisting('directories:', "  - '/a'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.ok(change);
      assert.match(change.newContent, /directories:\n {6}- '\/\*\*'\n/);
      assert.doesNotMatch(change.newContent, /'\/a'/);
    });

    it('keeps a directory that covers every manifest', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([['npm', new Set(['/'])]]),
        existing: createExisting("directory: '/'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.equal(change, null);
    });

    it('matches a directory literally', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([['npm', new Set(['/apps/[web]'])]]),
        existing: createExisting("directory: '/apps/[web]'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.equal(change, null);
    });

    it('keeps globbed directories that cover every manifest', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([
          ['npm', new Set(['/', '/apps/a', '/apps/b'])],
        ]),
        existing: createExisting('directories:', "  - '/'", "  - '/apps/*'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.equal(change, null);
    });

    it('keeps directories written without a leading or with a trailing slash', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([['npm', new Set(['/web', '/api'])]]),
        existing: createExisting('directories:', "  - 'web'", "  - '/api/'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.equal(change, null);
    });

    it('leaves `/**` alone', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map([['npm', new Set(['/', '/web'])]]),
        existing: createExisting('directories:', "  - '/**'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.equal(change, null);
    });

    it('leaves ecosystems without tracked directories alone', () => {
      const change = planDependabotChange({
        detected: new Set(['npm']),
        manifestDirsByEcosystem: new Map(),
        existing: createExisting("directory: '/web'"),
        template,
        defaultBranch: 'main',
        log,
      });
      assert.equal(change, null);
    });

    describe('with several entries per ecosystem', () => {
      const createEntry = (directory: string, ...lines: Array<string>) => [
        "  - package-ecosystem: 'npm'",
        `    directory: '${directory}'`,
        ...lines.map((line) => `    ${line}`),
        '    cooldown:',
        '      default-days: 7',
      ];
      const createExistingEntries = (...entries: Array<Array<string>>) => ({
        path: 'x',
        sha: 's',
        content: ['version: 2', 'updates:', ...entries.flat(), ''].join('\n'),
      });

      it('merges entries that miss a manifest into the first', () => {
        const change = planDependabotChange({
          detected: new Set(['npm']),
          manifestDirsByEcosystem: new Map([
            ['npm', new Set(['/web', '/api', '/worker'])],
          ]),
          existing: createExistingEntries(
            createEntry('/web', "versioning-strategy: 'increase'"),
            createEntry('/api', "versioning-strategy: 'lockfile-only'"),
          ),
          template,
          defaultBranch: 'main',
          log,
        });
        assert.ok(change);
        assert.equal(change.newContent.match(/package-ecosystem/g)?.length, 1);
        assert.match(change.newContent, /'increase'/);
        assert.doesNotMatch(
          change.newContent,
          /'lockfile-only'|'\/web'|'\/api'/,
        );
        assert.equal(
          change.summary,
          'updated `x`: set directories on `npm` to match the template',
        );
        assert.deepEqual(change.warnings, [
          'merged `npm` entries for `/web` and `/api` into one in `x`',
        ]);
      });

      it('keeps entries for other target branches apart', () => {
        const change = planDependabotChange({
          detected: new Set(['npm']),
          manifestDirsByEcosystem: new Map([['npm', new Set(['/', '/web'])]]),
          existing: createExistingEntries(
            createEntry('/', "target-branch: 'release'"),
            createEntry('/'),
          ),
          template,
          defaultBranch: 'main',
          log,
        });
        assert.ok(change);
        assert.equal(change.newContent.match(/package-ecosystem/g)?.length, 2);
        assert.equal(change.newContent.match(/'\/\*\*'/g)?.length, 2);
        assert.match(change.newContent, /target-branch: 'release'/);
        assert.deepEqual(change.warnings, []);
      });

      it('treats entries without a target branch as for the default one', () => {
        const change = planDependabotChange({
          detected: new Set(['npm']),
          manifestDirsByEcosystem: new Map([
            ['npm', new Set(['/web', '/api', '/worker'])],
          ]),
          existing: createExistingEntries(
            createEntry('/web'),
            createEntry('/api', "target-branch: 'main'"),
          ),
          template,
          defaultBranch: 'main',
          log,
        });
        assert.ok(change);
        assert.equal(change.newContent.match(/package-ecosystem/g)?.length, 1);
        assert.deepEqual(change.warnings, [
          'merged `npm` entries for `/web` and `/api` into one in `x`',
        ]);
      });

      it('checks coverage per target branch', () => {
        const change = planDependabotChange({
          detected: new Set(['npm']),
          manifestDirsByEcosystem: new Map([['npm', new Set(['/web'])]]),
          existing: createExistingEntries(
            createEntry('/', "target-branch: 'release'"),
            createEntry('/web'),
          ),
          template,
          defaultBranch: 'main',
          log,
        });
        assert.ok(change);
        assert.match(change.newContent, /target-branch: 'release'\n/);
        assert.equal(change.newContent.match(/'\/\*\*'/g)?.length, 1);
        assert.match(change.newContent, /directory: '\/web'/);
      });
    });
  });

  it('warns and skips a file whose updates is not a list', () => {
    const warningsBefore = warnings.length;
    const change = planDependabotChange({
      detected: new Set(['npm']),
      manifestDirsByEcosystem: new Map(),
      existing: {
        path: 'x',
        sha: 's',
        content: 'version: 2\nupdates:\n  package-ecosystem: npm\n',
      },
      template,
      defaultBranch: 'main',
      log,
    });
    assert.equal(change, null);
    assert.equal(warnings.length, warningsBefore + 1);
    assert.match(warnings.at(-1) ?? '', /non-list `updates`/);
  });

  it('warns and skips an unparseable file', () => {
    const warningsBefore = warnings.length;
    const change = planDependabotChange({
      detected: new Set(['npm']),
      manifestDirsByEcosystem: new Map(),
      existing: { path: 'x', sha: 's', content: 'version: [\n' },
      template,
      defaultBranch: 'main',
      log,
    });
    assert.equal(change, null);
    assert.equal(warnings.length, warningsBefore + 1);
    assert.match(
      warnings.at(-1) ?? '',
      /could not parse existing dependabot file/,
    );
  });
});
